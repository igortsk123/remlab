#!/usr/bin/env python3
"""Классы материала мебели (render-materials-01 шаг 2, T-20261117-14): порядок «характеристики → название → роль», отрицания,
общее «ткань» против названного вида, предпочтения роли, латинская «C» вместо «С», части (ножки), уверенность и «на проверку».
Запуск: python3 tools/assets/tests/test_material_class.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import material_class as MC  # noqa: E402

R = MC.load_rules()


def cls(role, name="", params=None):
    return MC.classify(R, {"role": role, "name": name, "params": params or {}})


def eq(got, want, what):
    assert got == want, f"{what}: ждали {want!r}, получили {got!r}"


# 1) характеристики главнее названия; обивка — по «Материал обивки», а не по каркасу
r = cls("диван", "Диван divan.ru Нумо Велюр Серый", {"Материал обивки": "рогожка", "Материал каркаса": "Фанера Массив ДВП"})
eq(r["class"], "rogozhka", "обивка из характеристик")
eq(r["stage"], "params", "стадия")
assert r["conflict"]["name"] == "velour" and r["needsReview"], "расхождение с названием помечено и идёт на проверку"
assert r["confidence"] < 0.9

# 2) общее «Ткань» уточняется видом из названия, каркас (фанера) обивку не перебивает
r = cls("диван", "Диван Босс велюр Монолит синий", {"Материал обивки": "Ткань", "Материал каркаса": "Фанера"})
eq((r["class"], r["stage"]), ("velour", "params+name"), "ткань + название")
r = cls("диван", "Диван Босс синий", {"Материал обивки": "Ткань", "Материал каркаса": "Фанера"})
eq(r["class"], "fabric", "общее «ткань» остаётся тканью, а не фанерой каркаса")

# 3) предпочтения роли: пуф «Основной материал: МДФ, Ткань» — ткань; стол «Металл, Стекло» — стекло
eq(cls("пуф", "Пуф", {"Основной материал": "МДФ, Ткань"})["class"], "fabric", "пуф")
eq(cls("столик", "Столик", {"Основной материал": "Металл, Стекло"})["class"], "glass", "стол со стеклом")

# 4) фасад главнее корпуса у корпусной мебели; МДФ в плёнке — не ЛДСП
eq(cls("шкаф", "Шкаф", {"Материал фасада": "МДФ 19 мм в пленке ПВХ", "Материал корпуса": "ЛДСП 16 мм"})["class"], "mdf_film", "фасад")
eq(cls("комод", "Комод", {"Материал фасада": "ЛДСП 16 мм МДФ 10 мм в пленке ПВХ"})["class"], "ldsp", "первое в тексте")

# 5) шпон: «МДФ с деревянным шпоном» — шпон, не массив
eq(cls("столик", "Столик", {"Материал столешницы": "МДФ с деревянным шпоном"})["class"], "wood_veneer", "шпон")
eq(cls("столик", "Столик", {"Материал столешницы": "Массив"})["class"], "wood_solid", "массив")

# 6) латинская «C» вместо кириллической
eq(cls("витрина", "Витрина", {"Материал фасада": "Cтекло Металл"})["class"], "glass", "Cтекло")

# 7) название: «кожа» с отрицанием и рогожка не путаются; цвет «Дуб» — не материал
eq(cls("кресло", "Кресло экокожа бежевое")["class"], "leather", "экокожа")
eq(cls("кресло", "Кресло рогожка бежевое")["class"], "rogozhka", "рогожка — не кожа")
eq(cls("кресло", "Кресло под кожу серое")["stage"], "role", "«под кожу» — не кожа")
eq(cls("комод", "Комод Дуб Барбера")["stage"], "role", "цвет «Дуб» — не материал")

# 8) роль: запасной класс с низкой уверенностью, без данных — «на проверку» с причиной
r = cls("кровать")
assert r["stage"] == "role" and r["needsReview"] and r["confidence"] < 0.5 and "evidenceGap" in r, "роль без данных"
r = cls("стул", "Стул ТС")
eq(r["class"], "neutral", "неопределимое — нейтральный")

# 9) ключи, не про видимую поверхность, игнорируются: ткань-подкладка, ручки
eq(cls("диван", "Диван", {"Техническая ткань": "спанбонд"})["stage"], "role", "подкладка не обивка")

# 10) части: ножки отдельно
r = cls("диван", "Диван", {"Материал обивки": "велюр", "Материал ножек (опор)": "Металл"})
eq(r["parts"]["legs"]["class"], "metal", "ножки")

# 10б) ножки без своего поля — по каркасу / основному материалу, дерево или металл, общее правило для сидений и кроватей (T-20261121-170/5)
r = cls("кресло", "Кресло", {"Материал обшивки": "Лен", "Материал каркаса": "Дерево, Полиуретан", "Основной материал": "Дерево"})
eq((r["class"], r["parts"]["legs"]["class"], r["parts"]["legs"].get("inferred")), ("fabric", "wood_solid", True), "кресло: лён и деревянный каркас — ножки дерево, помечено inferred")
r = cls("кровать", "Кровать", {"Материал обивки": "велюр", "Основной материал": "Металл"})
eq(r["parts"]["legs"]["class"], "metal", "кровать: основной материал — металл → ножки металл")
r = cls("диван", "Диван", {"Материал обивки": "велюр", "Материал каркаса": "фанера, древесные плиты"})
assert "legs" not in r.get("parts", {}), "«фанера, древесные плиты» — каркас под обивкой, как ДСП: ножками не становится"
r = cls("диван", "Диван", {"Материал обивки": "велюр", "Материал каркаса": "Фанера"})
assert "legs" not in r.get("parts", {}), "фанера сама по себе — тоже не ножки (одно правило на близкие слова)"
r = cls("диван", "Диван", {"Материал обивки": "велюр", "Материал каркаса": "ДСП, ЛДСП"})
assert "legs" not in r.get("parts", {}), "ДСП-каркас — не ножки"
r = cls("кресло", "Кресло", {"Материал обивки": "велюр", "Материал каркаса": "Металл, дерево"})
assert "legs" not in r.get("parts", {}), "каркас из металла и дерева — неоднозначно, ножки не угадываем"
r = cls("стул", "Стул", {"Материал обивки": "велюр", "Материал ножек": "Пластик", "Материал каркаса": "Дерево"})
eq((r["parts"]["legs"]["class"], "inferred" in r["parts"]["legs"]), ("plastic", False), "своё поле ножек главнее запасного")
r = cls("диван", "Диван", {"Материал обивки": "велюр", "Материал каркаса": "Ткань"})
assert "legs" not in r.get("parts", {}), "обивка в поле каркаса ножками не становится"

# 11) правила и результат согласованы (CI-проверка)
eq(MC.check(), 0, "check")
print("test_material_class: ок")

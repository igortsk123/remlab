"""T-171 задачи 2–3 (Fable otvet-33): звонок «стены ответа не лежат на листе» (walls_fail, в тени до субботы) + П7с и П3-«только лоджии» в справку (demote_to_info, p3_loggia_soft).
Стены: звонок «Ст» (walls_fail) на синтетике и П7с/П3 «только лоджии» (p3_loggia_soft проверяется явным включением — в пакете он ВЫКЛ). Регресс на сохранённых ответах t176 (R1, W0–W5) остался в work/ и идёт в сверке пакета.
Перенесён в репо из ~/remlab-logs/t171-nalozhenie (T-171/paket, rab-2): без сети, платного и чужих папок; правила — свой storozh_rules.json.
Запуск: python tools/floorplan/etazhi/test_steny.py (нужны numpy, pillow, shapely)."""
import glob
import json
import os
import types
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
for _name in ('nc_eval', 'neutral_names', 'words_on_sheet', 'vetka_a_eval', 'vetka_a_cmp_bd'):      # модули чужих папок: в CI их нет, сторожу эти проверки не нужны
    sys.modules.setdefault(_name, types.ModuleType(_name))
os.environ['SB_RULES'] = HERE + '/storozh_rules.json'      # правила — свои, из репо (выключатели кругов ВКЛ по умолчанию)
os.environ['LABELS_SRC'] = 'labels5'
import storozh as S  # noqa: E402

assert os.path.abspath(S.__file__) == os.path.join(HERE, 'storozh.py'), 'импортирован не рабочий storozh: %s' % S.__file__
RES = []


def check(name, cond, extra=''):
    RES.append((name, bool(cond)))
    print('%s  %s%s' % ('OK  ' if cond else 'FAIL', name, (' — ' + extra) if (extra and not cond) else ''))


def rules(**over):
    r = json.loads(json.dumps(S.RULES))
    r["overlay_fail"]["partial_alarm"] = {"enabled": False}      # круг 2г здесь не проверяем — он в test_krug2g.py
    for k, v in over.items():
        r[k].update(v) if isinstance(v, dict) else r.__setitem__(k, v)
    return r


R_ON = rules(walls_fail={'mode': 'on'}, demote_to_info={'enabled': True}, p3_loggia_soft={'enabled': True})      # П3-лоджия — круг 1, в пакете ВЫКЛ: здесь включаем явно
R_SHADOW = rules(walls_fail={'mode': 'shadow'})
R_OFF = rules(walls_fail={'mode': 'off'})
R_ALLOFF = rules(walls_fail={'mode': 'off'}, demote_to_info={'enabled': False}, p3_loggia_soft={'enabled': False})


# ---------- задача 3: П7с и П3 «только лоджии» ----------
P7S = [('П7с', 'контур не держится')]
P3L = ('П3', 'без входа (нет двери/прохода к нему от входной): Лоджия 1, Балкон')
P3Z = ('П3', 'без входа (нет двери/прохода к нему от входной): Санузел')
P3M = ('П3', 'без входа (нет двери/прохода к нему от входной): Лоджия 1, Санузел')
P3N = ('П3', 'нет входной двери квартиры (дверь, касающаяся ровно одной комнаты)')
P3T = ('П3', 'без входа (нет двери/прохода к нему от входной): Лоджия 1, Лоджия 2, Лоджия 3, Лоджия 4, Лоджия 5, Лоджия 6…')


CLEAN = {'на_линии': 0.80, 'стены': [{'стена': 'w1', 'длина_px': 1000.0, 'класс': 'на линии'}]}      # чистое наложение (круг 3): «легло», на линии ≥ 0,75, выдуманных 0 %


def sp(feats, rl, model='opus', ov='легло', ovd=None):
    b, i = S.split_features([(n, r, False) for n, r in feats], model, ov, rl, ov=ovd)
    return [n for n, _ in b], [n for n, _ in i]


check('T1 П7с единственный при ЧИСТОМ наложении → справка, не звонок (opus и gpt)', sp(P7S, R_ON, ovd=CLEAN) == ([], ['П7с']) and sp(P7S, R_ON, 'gpt', ovd=CLEAN) == ([], ['П7с']))
check('T1в −КОНТРОЛЬ круга 3: без чисел наложения (не чистое) П7с остаётся звонком', sp(P7S, R_ON) == (['П7с'], []))
check('T1б −КОНТРОЛЬ: demote_to_info выключен → П7с снова звонок (тест T1 краснеет)', sp(P7S, R_ALLOFF) == (['П7с'], []))
check('T2 П3 «без входа: только Лоджия/Балкон» → справка', sp([P3L], R_ON) == ([], ['П3']))
check('T3 П3 «без входа: Санузел» → звонок остался', sp([P3Z], R_ON) == (['П3'], []))
check('T3б П3 «Лоджия + Санузел» → звонок (смешанный список не смягчаем); «нет входной двери квартиры» → звонок; обрезанный список («…») → звонок',
      sp([P3M], R_ON) == (['П3'], []) and sp([P3N], R_ON) == (['П3'], []) and sp([P3T], R_ON) == (['П3'], []))
check('T3в −КОНТРОЛЬ: p3_loggia_soft выключен → «только Лоджия» снова звонок (T2 краснеет)', sp([P3L], R_ALLOFF) == (['П3'], []))
check('T4 другие признаки не тронуты: П7 и П10 остаются звонком; П3-лоджия при нелёгшем наложении — справка «рисунок не подтвердил» как раньше',
      sp([('П7', 'x'), ('П10', 'y')], R_ON) == (['П7', 'П10'], []) and sp([P3Z], R_ON, 'opus', 'не легло') == ([], ['П3']))
b, i = S.split_features([('П3', 'без входа (…): Санузел', False)], 'opus', 'не легло', R_ON)
check('T4б порядок и текст справки «рисунок не подтвердил» прежние', i and i[0][1].startswith('рисунок не подтвердил (наложение «не легло») — '))


# «не легло» и «частично» звонок «Ст» не трогает (там своё правило)
r_nl = S.finish({'класс': 'с подписями'}, [], [], 'частично', R_ON, ov={'на_линии': 0.2, 'лишнее_м': 20, 'стены': [{'стена': 'w1', 'длина_px': 100.0, 'класс': 'выдуманная'}]})
check('W6 звонок «Ст» только при «легло»: при «частично» его нет (исход — «сверено частично»)', 'Ст' not in r_nl['звонки'] and r_nl['исход'].startswith('сверено частично'))
r_nw = S.finish({'класс': 'с подписями'}, [], [], 'легло', R_ON, ov={'на_линии': 0.2, 'лишнее_м': 20})
check('W7 нет списка стен (walls.csv не прочитан) → звонок «Ст» не ставится, исход «готово»', r_nw['звонки'] == [] and r_nw['исход'].startswith('готово'))
for nm, ovx in (('доля выдуманных', {'на_линии': 0.9, 'лишнее_м': 1, 'стены': [{'стена': 'a', 'длина_px': 85.0, 'класс': 'на линии'}, {'стена': 'b', 'длина_px': 15.0, 'класс': 'выдуманная'}]}),
                ('лишнее 8 м', {'на_линии': 0.9, 'лишнее_м': 8.0, 'стены': [{'стена': 'a', 'длина_px': 100.0, 'класс': 'на линии'}]}),
                ('на линии 0,59', {'на_линии': 0.59, 'лишнее_м': 1, 'стены': [{'стена': 'a', 'длина_px': 100.0, 'класс': 'на линии'}]})):
    rr = S.finish({'класс': 'с подписями'}, [], [], 'легло', R_ON, ov=ovx)
    check('W8 порог «%s» срабатывает ровно на границе (≥15 %% / ≥8 м / <0,60)' % nm, rr['звонки'] == ['Ст'], rr['исход'][:80])
for nm, ovx in (('14 %', {'на_линии': 0.9, 'лишнее_м': 1, 'стены': [{'стена': 'a', 'длина_px': 86.0, 'класс': 'на линии'}, {'стена': 'b', 'длина_px': 14.0, 'класс': 'выдуманная'}]}),
                ('лишнее 7,9', {'на_линии': 0.9, 'лишнее_м': 7.9, 'стены': [{'стена': 'a', 'длина_px': 100.0, 'класс': 'на линии'}]}),
                ('на линии 0,60', {'на_линии': 0.6, 'лишнее_м': 1, 'стены': [{'стена': 'a', 'длина_px': 100.0, 'класс': 'на линии'}]})):
    rr = S.finish({'класс': 'с подписями'}, [], [], 'легло', R_ON, ov=ovx)
    check('W9 ниже порога «%s» — звонка нет' % nm, rr['звонки'] == [], rr['исход'][:80])

check('S1 по умолчанию (принятый набор): walls_fail.mode=on, demote_to_info ВЫКЛ, p3_loggia_soft ВЫКЛ', S.RULES['walls_fail'].get('mode') == 'on' and S.RULES["demote_to_info"].get("enabled") is False and S.RULES["p3_loggia_soft"].get('enabled') is False)

bad_n = sum(1 for _, ok in RES if not ok)
print('\nИТОГ: %d проверок, красных %d' % (len(RES), bad_n))
sys.exit(1 if bad_n else 0)

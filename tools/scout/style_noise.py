#!/usr/bin/env python3
"""Шум стиля (T-20261105-24): нейросеть ставит целые 0–10 и на повторе скачет на ±1 (замер T-20/2: средняя разница 0,48
на стиль, 5 из 6 смен тройки — при разрыве < 1). Здесь — чистые функции без сети и базы, их зовёт `style_score.py`:
  avg_runs   — среднее двух прогонов одной партии (дробный балл), «универсальный» — только если так сказали оба;
  settle     — порог смены: прежняя оценка держится, пока новая не обходит прежний порядок верхних стилей на ≥ 1,0;
  rule_shift — смена правил по материалу без нового платного прогона: сдвиг итога на разницу правил.
Самопроверка: ~/venvs/scout/bin/python style_noise.py --selftest
"""
import sys

THR = 1.0   # на сколько новый балл должен обойти прежний, чтобы тройка сменилась (владелец 05.11)
TOP = 4     # верх, порядок которого бережём: тройка показа считается из 5 вкладок (неоклассики в витрине нет) — тройка
            # из 5 лежит внутри четвёрки из 6, поэтому берём четыре по всем 6 стилям
EPS = 1e-9  # баллы округлены до 0,1 — сравнение без дробного мусора


def avg_runs(runs: list, n: int, names: list) -> tuple:
    """runs — ответы `llm_batch` на одну партию ({i: {стиль: балл, 'universal': bool}} или пустые при отказе).
    Возвращает ({i: усреднённая запись}, сколько позиций получили только один ответ из двух)."""
    out, single = {}, 0
    for i in range(n):
        got = [r[i] for r in runs if r and i in r]
        if not got: continue
        if len(got) < len(runs): single += 1
        out[i] = {st: sum(g[st] for g in got) / len(got) for st in names} | {'universal': all(g['universal'] for g in got)}
    return out, single


def rank(sc: dict, names: list) -> list:
    """Порядок стилей по баллу; ничья — порядок `names` (тот же, что у витрины и у листа golden)."""
    return sorted(names, key=lambda st: (-sc.get(st, 0), names.index(st)))


def settle(prev: dict | None, new: dict, names: list, thr: float = THR, top: int = TOP) -> tuple:
    """Порог смены. prev — прежняя запись модели (или None), new — только что посчитанная.
    Смена порядка верхних `top` стилей принимается, только если КАЖДЫЙ обгон в нём (стиль был ниже, стал выше)
    сделан с запасом ≥ thr по новым баллам; иначе держим прежнюю запись целиком (баллы и «универсальный»): частичная
    смена дала бы порядок, которого нет ни в одной оценке. Порядок не сменился — берём новую (баллы свежее).
    Возвращает (запись, держим_ли_прежнюю)."""
    if not prev or any(st not in prev for st in names): return new, False
    pr, nr = rank(prev, names), rank(new, names)
    if pr[:top] == nr[:top]: return new, False
    watch = set(pr[:top]) | set(nr[:top])
    pos = {st: i for i, st in enumerate(pr)}
    for a in nr:                    # a теперь выше b, а прежде был ниже — обгон
        for b in nr[nr.index(a) + 1:]:
            if pos[a] > pos[b] and (a in watch or b in watch) and new[a] - new[b] < thr - EPS:
                return prev, True
    return new, False


def rule_shift(prev: dict, rs_old: dict, rs_new: dict, names: list) -> dict:
    """Итог = база нейросети + правила×0,5 + CLIP×0,5 (`style_score.py`). Сменились только правила по материалу — база и
    CLIP те же, поэтому итог сдвигается на (новые − прежние)×0,5 без нового прогона. Неточность — только у баллов, упёртых
    в 0 или 10 прежде."""
    out = dict(prev)
    for st in names:
        out[st] = round(max(0, min(10, prev[st] + (rs_new[st] - rs_old[st]) * 0.5)), 1)
    return out


def _selftest() -> int:
    N = ['сканди', 'современный', 'минимализм', 'лофт', 'неоклассика', 'джапанди']
    fails = 0

    def ok(cond, msg):
        nonlocal fails
        print(('OK   ' if cond else 'FAIL ') + msg)
        fails += not cond

    def sc(*v, u=False):
        return dict(zip(N, v)) | {'universal': u}

    # среднее двух прогонов — дробный балл; «универсальный» — только у двух «да»
    r1 = {0: sc(7, 6, 5, 2, 3, 8, u=True), 1: sc(5, 5, 5, 5, 5, 5, u=True)}
    r2 = {0: sc(8, 6, 4, 2, 3, 7, u=False), 1: sc(5, 6, 5, 5, 5, 5, u=True)}
    a, single = avg_runs([r1, r2], 2, N)
    ok(a[0]['сканди'] == 7.5 and a[0]['минимализм'] == 4.5 and a[0]['джапанди'] == 7.5, 'среднее двух прогонов: 7 и 8 → 7,5')
    ok(a[0]['universal'] is False and a[1]['universal'] is True, 'универсальный — только если оба прогона сказали «да»')
    ok(single == 0, 'оба ответа на месте — одиночных нет')
    a, single = avg_runs([r1, {}], 2, N)
    ok(a[0]['сканди'] == 7 and single == 2, 'второй прогон упал — берём один ответ и считаем одиночные')
    a, single = avg_runs([{1: r1[1]}, {}], 2, N)
    ok(0 not in a and 1 in a, 'позиции без ответа нет в итоге — уйдёт в «правила+CLIP», как раньше')

    prev = sc(7.0, 6.0, 5.0, 3.0, 2.0, 4.0)        # тройка: сканди, современный, минимализм
    # обгон на 0,9 — держим прежнюю (и баллы, и тройку)
    new = sc(6.0, 6.9, 5.0, 3.0, 2.0, 4.0)
    r, held = settle(prev, new, N)
    ok(held and r is prev, 'порог: современный обходит сканди на 0,9 — тройка прежняя')
    # обгон ровно на 1,0 — меняем
    new = sc(6.0, 7.0, 5.0, 3.0, 2.0, 4.0)
    r, held = settle(prev, new, N)
    ok(not held and r is new, 'порог: обгон ровно на 1,0 — тройка сменилась')
    # новый в тройке на 0,9 выше выбывшего — держим; на 1,0 — меняем
    new = sc(7.0, 6.0, 4.1, 3.0, 2.0, 5.0)
    ok(settle(prev, new, N)[1], 'джапанди входит в тройку на 0,9 выше минимализма — держим')
    new = sc(7.0, 6.0, 4.0, 3.0, 2.0, 5.0)
    ok(not settle(prev, new, N)[1], 'джапанди входит в тройку на 1,0 выше — меняем')
    # порядок верха тот же — берём новые баллы, даже если они сдвинулись
    new = sc(7.5, 5.5, 5.0, 3.0, 2.0, 4.0)
    r, held = settle(prev, new, N)
    ok(not held and r is new, 'порядок верха не сменился — свежие баллы приняты')
    # ничья с прежним порядком — не обгон с запасом: держим
    new = sc(6.5, 6.5, 5.0, 3.0, 2.0, 4.0)
    ok(not settle(prev, new, N)[1], 'ничья 6,5/6,5 — порядок по вкладкам тот же, сканди первый: смены нет')
    new = sc(6.5, 6.5, 5.0, 3.0, 2.0, 4.0)
    p2 = sc(6.0, 7.0, 5.0, 3.0, 2.0, 4.0)       # прежде современный был первым — ничья вернула бы сканди
    ok(settle(p2, new, N)[1], 'ничья, которая перевернула бы порядок, — держим прежний')
    # обгоны ниже верха не держат свежие баллы
    new = sc(7.0, 6.0, 5.0, 2.0, 2.5, 3.0)       # неоклассика обошла лофт на 0,5 в хвосте
    ok(not settle(prev, new, N)[1], 'обгон в хвосте (5–6 места) не держит свежую оценку')
    # четвёртое место бережём: тройка показа (без неоклассики) берётся из четвёрки
    prev4 = sc(7.0, 6.0, 5.0, 3.0, 8.0, 4.5)     # неоклассика первая; показ: сканди, современный, минимализм
    new4 = sc(7.0, 6.0, 4.5, 3.0, 8.0, 5.0)      # джапанди обходит минимализм на 0,5 — показ сменился бы
    ok(settle(prev4, new4, N)[1], 'неоклассика наверху: смена 3-го места показа на 0,5 — держим')
    # смешанный случай: один обгон с запасом, другой без — держим целиком
    new = sc(5.0, 7.0, 5.0, 3.0, 2.0, 5.5)
    ok(settle(prev, new, N)[1], 'один обгон на 2,0, другой на 0,5 — держим прежнюю целиком')
    ok(settle(None, new, N) == (new, False), 'прежней оценки нет — берём новую')

    # правила по материалу: сдвиг без прогона
    rs0 = {st: 0.0 for st in N}
    rs1 = rs0 | {'лофт': 4.0}
    s = rule_shift(prev | {'src': 'llm+rules'}, rs0, rs1, N)
    ok(s['лофт'] == 5.0 and s['сканди'] == 7.0 and s['src'] == 'llm+rules', 'правило «металл» +4 → лофт +2 без прогона')
    s = rule_shift(sc(7, 6, 5, 9.5, 2, 4), rs0, rs1, N)
    ok(s['лофт'] == 10, 'сдвиг упирается в 10')
    print(f'FAILS {fails}')
    return fails


if __name__ == '__main__':
    if '--selftest' in sys.argv: sys.exit(1 if _selftest() else 0)
    print(__doc__)

"""Стиль/дерево/металл/фактура из НАЗВАНИЯ товара (бесплатно, без API).
Дизайнерские правила: один стиль (или совместимая пара), один тон дерева, один металл."""
import re
STYLES={
 'лофт':      r'лофт|loft|индастри|гранж|грандж|цемент|бетон',
 'сканди':    r'сканди|scandi|сканд|nord|нордик|хюгге|стокгольм|осло|берген',
 'классика':  r'классик|барокко|версал|ампир|каретн|честер|chester|вензел|резн|патин',
 'неоклассика':r'неоклассик|капитоне|стёжк|стежк',
 'прованс':   r'прованс|кантри|шебби|ротанг|плетён|плетен',
 'минимализм':r'минимал|слим|smart|линеар',
 'современный':r'модерн|современ|милан|сити|скай|тренд|фьюжн',
 'джапанди':  r'джапанди|japandi|ваби|японск|дзен|\bzen\b|бамбук',
}
WOOD={
 'орех':   r'орех|walnut|итальянск\w+ орех',
 'дуб':    r'\bдуб\b|сонома|oak|крафт|вотан|галифакс',
 'венге':  r'венге|шоколад|мокко|эбен',
 'белёное':r'бел[её]н|выбелен|белый ясень|ясень бел|анкор бел|рамух бел|жемчужн',
 'светлое':r'\bбук\b|бер[её]за|сосна|ольха|латте|капучино|дуб молочн|ваниль',
}
METAL={
 'латунь': r'латун|золот|бронз|brass|gold|шампань',
 'чёрный': r'ч[её]рн\w{0,4} (металл|каркас|опор|нож|основани)|black|мурен',
 'хром':   r'хром|никел|нержав|серебрист|сталь',
}
FABRIC={
 'рогожка':r'рогожк',
 'велюр':  r'велюр|микровелюр',
 'шенилл': r'шенилл',
 'экокожа':r'экокож|кожзам|иск\w* кожа',
 'бархат': r'бархат',
 'букле':  r'букле',
}
COMPAT={('сканди','минимализм'),('сканди','современный'),('минимализм','современный'),
        ('классика','неоклассика'),('неоклассика','прованс'),('лофт','минимализм'),
        ('лофт','современный'),('сканди','прованс'),
        ('джапанди','сканди'),('джапанди','минимализм'),('неоклассика','современный')}
def tag(name):
    nl=(name or '').lower()
    return {k:next((s for s,rx in dic.items() if re.search(rx,nl)),None)
            for k,dic in (('style',STYLES),('wood',WOOD),('metal',METAL),('fabric',FABRIC))}
def style_ok(a,b):
    if not a or not b or a==b: return True
    return (a,b) in COMPAT or (b,a) in COMPAT

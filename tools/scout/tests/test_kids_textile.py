"""Отсев детского ТЕКСТИЛЯ по словам (T-20261017-01, demo-05 «детские ковры»): слова из названий детских ковров (`KIDS_TEXTILE`)
действуют только на ковры и текстиль, общий `KIDS` («детск…») — на все роли. Без сети и базы.
    ~/venvs/scout/bin/python tools/scout/tests/test_kids_textile.py"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import category_map as C  # noqa: E402

fails = 0


def check(name, cond):
    global fails
    print(('OK   ' if cond else 'FAIL ') + name)
    fails += 0 if cond else 1


# (а) детский текстиль ловится словарём текстиля
check('«Милна Фанни … let\'s play» — словарь текстиля', bool(C.KIDS_TEXTILE.search("Ковер divan.ru Милна Фанни Серый 160x230 let's play")))
check('«Милна Фанни … let\'s play» — детский как ковёр', C.is_kids("Ковер divan.ru Милна Фанни Серый 160x230 let's play", 'ковёр'))
# «Джой» в каталоге называется без «радуги» («Ковер divan.ru Джой Розовый 105x87») — его ловит картинка (`rug_kids.py`), не слова;
# слова «радуга» в словаре нет: в каталоге оно только у детского постера (замер 17.10)
check('«Ковер divan.ru Джой Розовый 105x87» словами НЕ ловится — ловит картинка (rug_kids), не слова',
      not C.is_kids('Ковер divan.ru Джой Розовый 105x87', 'ковёр'))
# ложные срабатывания после замены голого «дорог» узкими словами
check('«Ковровая дорожка divan.ru Лунс 80x200» — не детский (ковёр)', not C.is_kids('Ковровая дорожка divan.ru Лунс 80x200', 'ковёр'))
check('«Коврик Play mat 120x180» — детский (ковёр, слово play)', C.is_kids('Коврик Play mat 120x180', 'ковёр'))
# (б) те же слова на мебель и часы не действуют
check('«Диван Тут Рядом Космос» — не детский', not C.is_kids('Диван прямой divan.ru Тут Рядом Космос Рогожка Серый', 'диван'))
check('«Часы настенные Цифры» — не детские', not C.is_kids('Часы настенные JJT цветные цифры 50х50 см', 'часы'))
check('«космос» словарём текстиля ловится, но роль не текстиль — не детский', bool(C.KIDS_TEXTILE.search('Космос')) and not C.is_kids('Кресло Космос-1', 'кресло'))
# (в) общий словарь по-прежнему ловит «детский» в любой роли
check('общий KIDS: «Стул детский» — детский', C.is_kids('Стул детский Котёнок', 'стул'))
check('общий KIDS: «Ковер детский» — детский', C.is_kids('Ковер детский 100x150', 'ковёр'))
check('общий KIDS без роли — как раньше', C.is_kids('Светильник детский Облако'))
print('всё зелёное' if not fails else f'красных: {fails}')
sys.exit(1 if fails else 0)

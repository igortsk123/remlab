#!/usr/bin/env python3
"""Размеры КРОВАТИ: внешний габарит отдельно от спального места (план b2b-10, этап 2; разбор Codex 14.10).

ЗАЧЕМ. Мебельная конвенция осей (`dim_resolver`) для кровати неверна: «160×200» в названии — это спальное место,
а на полу кровать занимает 173×230 (divan.ru «Кейт 160»). Перепутать — значит обещать в спальне проход, которого нет.

ЧТО ПИШУТ МАГАЗИНЫ (замер фидов 14.10):
- divan.ru (112923): «Размеры: Ширина/Длина/Высота габаритная» + «Спальное место: Ширина/Длина спального места»
  + «Размер спального места, см» = «180x200» — 1 231 кровать, почти у всех оба набора.
- МногоМебели/ДиванБосс (114667/114082): «Ширина/Длина/Высота» = габарит, «Ширина/Длина спального места» — бывают
  ПЕРЕСТАВЛЕНЫ (Белла: ширина 200, длина 160) — спальное место нормализуем: ширина = меньшее, длина = большее.
- Орматек (93965): «Ширина/Длина» — общие числа линейки (у «Skandy Base 80x190» — 200×200), габарит недостоверен.
ПРАВИЛО: габарит принимаем, только если он не меньше спального места по обеим осям; иначе `footprint_ok=False` —
кровать показывается в каталоге с размером спального места, но в расстановку не допускается (не выдумываем).

  python3 bed_dims.py --selftest
"""
import re
import sys

# Рама шире спального места не больше чем на 70 см, длиннее — на 60 (замер 14.10 по честным магазинам: divan.ru,
# МногоМебели, ДиванБосс — максимум 65 и 52). Больше — это габарит линейки, а не этой кровати (Орматек «80×190» с
# шириной 200).
MAX_FRAME_W, MAX_FRAME_D = 70.0, 60.0
_NUM = re.compile(r'(\d+(?:[.,]\d+)?)')
_PAIR = re.compile(r'(\d{2,3})\s*[xх×*]\s*(\d{2,3})', re.I)


def _cm(v) -> float | None:
    """'230см' / '230' / '190см 200см' (берём первое) → 230.0; мусор → None."""
    if v is None:
        return None
    m = _NUM.search(str(v))
    if not m:
        return None
    x = float(m.group(1).replace(',', '.'))
    return x if 30 <= x <= 400 else None


def _first(p: dict, *keys: str) -> float | None:
    for k in keys:
        if k in p:
            v = _cm(p[k])
            if v is not None:
                return v
    return None


def parse(params: dict, name: str = '') -> dict:
    """→ {w_cm, d_cm, h_cm, sleep_w_cm, sleep_l_cm, footprint_ok, why}. Ось w — ширина (поперёк кровати),
    d — длина (от изголовья к ногам), как у мебели «ширина × глубина»."""
    p = params or {}
    w = _first(p, 'Размеры: Ширина габаритная', 'Ширина')
    d = _first(p, 'Размеры: Длина габаритная', 'Длина')
    h = _first(p, 'Размеры: Высота габаритная', 'Высота')
    sw = _first(p, 'Спальное место: Ширина спального места', 'Ширина спального места')
    sl = _first(p, 'Спальное место: Длина спального места', 'Длина спального места')
    if sw is None or sl is None:
        m = _PAIR.search(str(p.get('Размер спального места, см') or '')) or _PAIR.search(name or '')
        if m:
            sw, sl = float(m.group(1)), float(m.group(2))
    if sw is not None and sl is not None and sw > sl:
        sw, sl = sl, sw                                      # переставлены магазином (МногоМебели «Белла»)
    out = {'w_cm': w, 'd_cm': d, 'h_cm': h, 'sleep_w_cm': sw, 'sleep_l_cm': sl, 'footprint_ok': False, 'why': ''}
    if w is None or d is None:
        out['why'] = 'нет габарита'
    elif sw is None or sl is None:
        out['why'] = 'нет спального места — габарит не с чем сверить'
    elif w < sw or d < sl:
        out['why'] = f'габарит {w:.0f}×{d:.0f} меньше спального места {sw:.0f}×{sl:.0f} — числа линейки, не этой кровати'
    elif w == sw and d == sl:
        out['why'] = f'габарит {w:.0f}×{d:.0f} равен спальному месту — магазин, скорее всего, указал размер матраса'
    elif w - sw > MAX_FRAME_W or d - sl > MAX_FRAME_D:
        out['why'] = f'габарит {w:.0f}×{d:.0f} слишком велик для спального места {sw:.0f}×{sl:.0f} — числа линейки'
    else:
        out['footprint_ok'] = True
    return out


def _selftest() -> int:
    bad = 0

    def ok(name: str, cond: bool) -> None:
        nonlocal bad
        print(('OK   ' if cond else 'FAIL ') + name)
        bad += 0 if cond else 1

    kate = parse({'Размеры: Длина габаритная': '230см', 'Размеры: Ширина габаритная': '173см', 'Размеры: Высота габаритная': '93см',
                  'Спальное место: Длина спального места': '200см', 'Спальное место: Ширина спального места': '140см'},
                 'Кровать divan.ru Кейт 140')
    ok('divan.ru: габарит 173×230, спальное 140×200, в расстановку можно',
       (kate['w_cm'], kate['d_cm'], kate['sleep_w_cm'], kate['sleep_l_cm'], kate['footprint_ok']) == (173, 230, 140, 200, True))
    bella = parse({'Длина': '209', 'Ширина': '167', 'Высота': '79', 'Ширина спального места': '200', 'Длина спального места': '160'})
    ok('МногоМебели: переставленное спальное место нормализуется (160×200)', (bella['sleep_w_cm'], bella['sleep_l_cm']) == (160, 200))
    ok('МногоМебели: габарит 167×209 проходит сверку', bella['footprint_ok'])
    skandy = parse({'Ширина': '200см', 'Длина': '200см', 'Ширина спального места': '200см'}, 'Кровать Skandy Base (ЛДСП Белый) 80x190')
    ok('Орматек: «200×200» у кровати 80×190 — спальное место из названия', (skandy['sleep_w_cm'], skandy['sleep_l_cm']) in ((80, 190), (200, 200)))
    prado = parse({'Ширина': '200см', 'Длина': '220см', 'Ширина спального места': '200см'}, 'Кровать Орматек Prado')
    ok('Орматек: нет длины спального места → в расстановку нельзя', not prado['footprint_ok'])
    only_name = parse({}, 'Кровать Lite 160x200')
    ok('только «160x200» в названии — спальное место, габарита нет', (only_name['sleep_w_cm'], only_name['sleep_l_cm'], only_name['footprint_ok'], only_name['w_cm']) == (160, 200, False, None))
    anri = parse({'Ширина': '200см', 'Длина': '190см'}, 'Кровать Орматек Анри 80x190')
    ok('рама шире спального на 120 см — габарит линейки, в расстановку нельзя', not anri['footprint_ok'])
    same = parse({'Ширина': '80', 'Длина': '200', 'Ширина спального места': '80', 'Длина спального места': '200'})
    ok('габарит = спальному месту — это матрас, в расстановку нельзя', not same['footprint_ok'])
    multi = parse({'Ширина': '200см', 'Длина': '190см 200см'})
    ok('«190см 200см» — первое число', multi['d_cm'] == 190)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(_selftest() if '--selftest' in sys.argv else 0)

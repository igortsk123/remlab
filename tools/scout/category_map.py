# СТОЛЫ В СМЕШАННЫХ ВЕТКАХ — тип по названию (T-20261020-23, Codex 20.10). Общее `^стол\s` в ALLOW писало в обеденные
# любой «Стол …»: «Стол кофейный Glasar 81×81×40» встал обеденным в демо сканди, «Стол рабочий» и «Стол барный» — в ленту.
# Тип — слово ВПЛОТНУЮ к «стол» (пробел или дефис, с границами слова): «кофейный» в хвосте названия — цвет
# («Обеденный стол TC Caterina кофейный»), «кофейня» — не тип. Порядок: «… для обеденного стола» — принадлежность,
# не стол → двойное назначение (трансформер) → не гостиная (рабочий, барный…) → явное «обеденный» → журнальный.
_TABLE = r'стол(?:ы|а|ик|ики)?'
_SEP = r'[\s-]+'


def _near_table(types: str) -> re.Pattern:
    return re.compile(rf'\b{_TABLE}{_SEP}(?:{types})\b|\b(?:{types}){_SEP}{_TABLE}\b', re.I)


TABLE_WORD = re.compile(rf'\b{_TABLE}\b', re.I)
TABLE_FOR = re.compile(rf'\bдля{_SEP}(?:\w+{_SEP}){{0,2}}{_TABLE}\b', re.I)
# ДВОЙНОЕ НАЗНАЧЕНИЕ — из автоподбора вон (карантин): меш и габарит сложенного журнального не совпадают с обеденным
TABLE_DUAL = re.compile(r'\bтрансформер\w*\b|\bжурнальн\w*-обеденн|\bобеденн\w*-журнальн', re.I)
TABLE_NOT_LIVING = _near_table(r'рабоч(?:ий|ая|ие|его)|письменн\w*|компьютерн\w*|барн(?:ый|ая|ые|ого)|'
                               r'консол\w*|туалетн\w*|сервировочн\w*')
TABLE_DINING = re.compile(r'\bобеденн\w*\b', re.I)
TABLE_COFFEE = _near_table(r'кофейн(?:ый|ая|ое|ые|ого|ой)|журнальн\w*|приставн\w*|придиванн\w*')


def table_role(name: str) -> tuple[bool, str | None]:
    """(решено ли правилом столов, роль). Не решено — роль даёт общий `classify`."""
    low = (name or '').lower()
    if TABLE_FOR.search(low):
        return True, classify(TABLE_FOR.sub(' ', low))[0]     # «Стул для обеденного стола» — стул
    if not TABLE_WORD.search(low):
        return False, None
    if TABLE_DUAL.search(low) or TABLE_NOT_LIVING.search(low):
        return True, None
    if TABLE_DINING.search(low):
        return True, 'стол обеденный'
    if TABLE_COFFEE.search(low):
        return True, 'столик'
    return False, None


def dining_name_bad(name: str) -> bool:
    """Название говорит, что это НЕ обеденный стол — для сторожей роли «стол обеденный» (`unfit`, tests_chain)."""
    low = (name or '').lower()
    return bool(TABLE_DUAL.search(low) or TABLE_NOT_LIVING.search(low)
                or (TABLE_COFFEE.search(low) and not TABLE_DINING.search(low)))


def role_by_name(name: str) -> str | None:
    """Роль по названию товара (только для MIXED-веток): те же DENY/ALLOW, что для путей категорий, плюс правило столов."""
    if is_kids(name):
        return None
    role, why = classify(name or '')
    if role is None and why.startswith('исключено'):
        return None                                           # DENY сильнее (подсветка, детское, офис…)
    decided, trole = table_role(name)
    return trole if decided else role


# СВЕТ: РОЛЬ УТОЧНЯЕТСЯ ПО ТИПУ ТОВАРА (план catalog-holes-bank Н2а, Codex 23.10). Ветка «Настенно-потолочные светильники»
# (99272, 1 670) целиком идёт в люстры (ALLOW `настенно-потолочн`), а внутри — встраиваемые, трековые, линейные, подсветка
# картин и зеркал (241) и настенные бра (97); среди низких «люстр» — пульты, реле, блоки питания. Карта категорий параметров
# товара не видит, поэтому решает `load3.assign` по параметру «Тип» (иначе «Тип товара»). Нет типа — то же правило по
# НАЗВАНИЮ, но только на принадлежности (пульт/реле/преобразователь — у них «Тип» часто пуст), не на виды светильников.
LIGHT_ROLES = frozenset({'люстра', 'бра', 'лампа', 'торшер'})
LIGHT_NOT_LIVING = re.compile(r'встраив|треков|линейн|подсветк|лестничн', re.I)
# Принадлежность — слово В НАЧАЛЕ типа/названия: «Люстра … с пультом», «Светильник … с драйвером» — светильники (63 таких)
LIGHT_ACCESSORY = re.compile(r'^\s*(?:пульт|реле\b|блок\w* питан|преобразовател|трансформатор|драйвер|контроллер|аксессуар|'
                             r'коннектор|основание для|шинопровод|адаптер)', re.I)
WALL_LIGHT_TYPE = 'светильник настенный'   # ТОЧНО: «Светильник настенно-потолочный» — потолочный, не бра


def light_role(role: str | None, name: str, params: dict | None) -> tuple[str | None, str | None]:
    """(роль, причина смены) для световых ролей; причина None — роль не менялась."""
    if role not in LIGHT_ROLES:
        return role, None
    p = params or {}
    kind = (p.get('Тип') or p.get('Тип товара') or '').strip()
    if kind:
        if LIGHT_ACCESSORY.search(kind):
            return None, f'тип «{kind}» — принадлежность, не светильник'
        if LIGHT_NOT_LIVING.search(kind):
            return None, f'тип «{kind}» — точечный/технический свет, не для комплекта гостиной'
        if role == 'люстра' and kind.lower() == WALL_LIGHT_TYPE:
            return 'бра', f'тип «{kind}»'
        return role, None
    if LIGHT_ACCESSORY.search(name or ''):
        return None, 'принадлежность по названию (типа нет)'
    return role, None


def classify(path: str) -> tuple[str | None, str]:
    """(роль или None, причина). Запреты сильнее разрешений, кроме точечных ALLOW_FIRST."""
    low = path.lower()
    for rx, role in ALLOW_FIRST:
        if re.search(rx, low) and not re.search(r'рассад|уличн', low):
            return role, 'allow-first (единственный источник роли)'
    for rx, why in DENY:
        if re.search(rx, low):
            return None, f'исключено: {why}'
    # 17.08 (Q6a-смежное): сначала ЛИСТ категории, потом полный путь — иначе «Диваны и кресла / Кресла»
    # (divan.ru 442, 335 офферов) размечалось как «диван» по родителю, и кресел divan.ru в пуле не было
    # (компактные пары pod искались только у nonton)
    leaf = low.split('/')[-1].strip()
    for rx, role in ALLOW:
        if re.search(rx, leaf):
            return role, 'по листу категории фида'
    for rx, role in ALLOW:
        if re.search(rx, low):
            return role, 'по категории фида'
    return None, 'не относится к гостиной'


def build() -> dict:
    cats = json.load(open(TAX))
    out = {}
    for key, c in cats.items():
        role, why = OVERRIDES.get(key) or classify(c['path'])
        if key in MIXED:
            role, why = None, 'смешанная ветка: роль по названию товара (MIXED, load3)'
        out[key] = {'mid': c['mid'], 'id': c['id'], 'path': c['path'],
                    'offers': c['offers'], 'role': role, 'why': why}
    json.dump(out, open(OUT, 'w'), ensure_ascii=False)
    by_role: dict[str, int] = {}
    denied: dict[str, int] = {}
    for c in out.values():
        if c['role']:
            by_role[c['role']] = by_role.get(c['role'], 0) + c['offers']
        elif c['offers']:
            denied[c['why']] = denied.get(c['why'], 0) + c['offers']
    print(f'категорий разобрано: {len(out)}\n')
    print('ПУЛ ГОСТИНОЙ по категориям фида:')
    for r, n in sorted(by_role.items(), key=lambda kv: -kv[1]):
        print(f'  {n:>6}  {r}')
    print(f'\n  ИТОГО в пуле: {sum(by_role.values())}')
    print('\nИСКЛЮЧЕНО:')
    for w, n in sorted(denied.items(), key=lambda kv: -kv[1])[:14]:
        print(f'  {n:>6}  {w}')
    return out


def review(limit: int = 25) -> None:
    """Крупные категории, оставшиеся без роли — по ним решение ещё не принято."""
    out = json.load(open(OUT)) if os.path.exists(OUT) else build()
    show_all = '--all' in sys.argv     # и ветки, убитые DENY: ошибочный запрет иначе невидим
    rest = [c for c in out.values()
            if not c['role'] and c['offers'] > 30 and (show_all or c['why'] == 'не относится к гостиной')]
    rest.sort(key=lambda c: -c['offers'])
    print(f'категорий без решения (товаров > 30): {len(rest)}\n')
    for c in rest[:limit]:
        print(f'  {c["offers"]:>6}  [{c["mid"]}] {c["path"][:76]}')


def apply() -> None:
    """Записать роль из категории в БД — колонка products.cat_role."""
    out = json.load(open(OUT)) if os.path.exists(OUT) else build()
    vals = [f"({c['mid']},'{c['id']}','{c['role']}')" for c in out.values() if c['role']]
    kids_sql = ("update products set cat_role=null where cat_role is not null and name ~* "
                "'детск|для детей|машинк|мультфильм|единорог|русалк|дракош|человек-паук|"
                "принцесс|микки|лего|барби|смешарик|котят|щенячий|фиксик|подростков';")
    mixed_sql = ' or '.join(f"(p.shop_mid={k.split(':')[0]} and p.category_id::text='{k.split(':')[1]}')" for k in MIXED) or 'false'
    before = subprocess.run(PSQL, capture_output=True, text=True,
                            input="select count(*) from products where cat_role is not null").stdout.strip()
    # одна транзакция и проверка кода возврата: раньше сброс всех ролей и их восстановление шли
    # отдельными запросами без проверки, падение посередине оставляло каталог без ролей (Codex 03.09)
    r = subprocess.run(PSQL, input=(
        "begin;"
        "alter table products add column if not exists cat_role text;"
        "create index if not exists idx_products_cat_role on products (cat_role);"
        f"update products p set cat_role=null where cat_role is not null and not ({mixed_sql});"
        f"update products p set cat_role=v.role from (values {','.join(vals)}) "
        f"as v(mid, cid, role) where p.shop_mid=v.mid and p.category_id::text=v.cid and not ({mixed_sql});"
        + kids_sql + "commit;"
    ), capture_output=True, text=True)
    if r.returncode != 0:
        print('СТОП: --apply откатился, роли не изменены:', r.stderr[:400])
        sys.exit(1)
    after = subprocess.run(PSQL, capture_output=True, text=True,
                           input="select count(*) from products where cat_role is not null").stdout.strip()
    print(f'товаров с ролью: было {before}, стало {after} (MIXED-ветки не трогаем — их роли ставит load3)')
    r = subprocess.run(PSQL, capture_output=True, text=True, input=
                       "select cat_role, count(*) from products where cat_role is not null "
                       "and in_stock group by 1 order by 2 desc")
    print('роли из категорий записаны в products.cat_role:\n')
    for line in r.stdout.strip().split('\n'):
        f = line.split('\x1f')
        if len(f) == 2:
            print(f'  {f[1]:>6}  {f[0]}')



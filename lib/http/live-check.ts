// Служебная метка живых проверок прода (T-20261018-18): ночные тесты (`playwright.live.config.ts` → `extraHTTPHeaders`) ходят
// по сайту как покупатель и шлют `x-remlab-check: 1` со всеми запросами страницы. По такому запросу сервер отвечает как обычно,
// но не пишет счётчики отчёта застройщика, события ссылки менеджера и серверную аналитику — там должны быть только люди.
// Подделка посторонним ничем не грозит: метка лишь убирает его же события. Проверка — только этой функцией, без копий.

export const LIVE_CHECK_HEADER = "x-remlab-check";

/** true — запрос от живой проверки: отвечать как обычно, счётчики и события не писать. */
export function isLiveCheck(headers: Pick<Headers, "get">): boolean {
  return headers.get(LIVE_CHECK_HEADER) === "1";
}
